CREATE TABLE students(
 student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_number VARCHAR(30) NOT NULL UNIQUE,full_name VARCHAR(120) NOT NULL
);
CREATE TABLE rooms(
 room_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_number VARCHAR(20) NOT NULL UNIQUE,capacity INT NOT NULL CHECK(capacity>0)
);
CREATE TABLE allocations(
 allocation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id INT NOT NULL REFERENCES students(student_id),room_id INT NOT NULL REFERENCES rooms(room_id),
 allocated_on DATE NOT NULL,released_on DATE,
 status VARCHAR(10) NOT NULL CHECK(status IN('ACTIVE','ENDED')),
 CHECK((status='ACTIVE' AND released_on IS NULL) OR (status='ENDED' AND released_on IS NOT NULL))
);
CREATE TABLE occupancy_snapshot(
 snapshot_date DATE NOT NULL,room_id INT NOT NULL REFERENCES rooms(room_id),
 occupied_beds INT NOT NULL,free_beds INT NOT NULL,
 PRIMARY KEY(snapshot_date,room_id)
);
